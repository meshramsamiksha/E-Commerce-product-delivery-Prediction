"""### 4.2 Categorical features vs delivery outcome"""

# Loop over the four categorical columns and plot counts split by the target
cat_cols = ["Warehouse_block", "Mode_of_Shipment", "Product_importance", "Gender"]

fig, axes = plt.subplots(2, 2, figsize=(11, 7))          # 2x2 grid of subplots
for ax, col in zip(axes.ravel(), cat_cols):              # pair each axis with one column
    sns.countplot(x=col, hue="Late", data=df, palette=PALETTE, ax=ax)
    ax.set_title(f"{col} vs delivery outcome")           # subplot title
    ax.legend(title="Late", labels=["On time", "Late"], fontsize=8)
plt.tight_layout(); plt.savefig("figs/02_categorical.png"); plt.show()

# Numeric view: late-delivery percentage inside each category
for col in cat_cols:
    share = (df.groupby(col)["Late"].mean()*100).round(1)      # mean of 0/1 target = % late
    RESULTS[f"late_by_{col}"] = share.to_dict()                # keep for the slides
