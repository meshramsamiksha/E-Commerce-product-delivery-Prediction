"""### 4.3 Numerical features vs delivery outcome"""

num_cols = ["Customer_care_calls", "Customer_rating", "Cost_of_the_Product",
            "Prior_purchases", "Discount_offered", "Weight_in_gms"]

# Histogram of every numeric feature, coloured by the target class
fig, axes = plt.subplots(2, 3, figsize=(13, 6.5))
for ax, col in zip(axes.ravel(), num_cols):
    sns.histplot(data=df, x=col, hue="Late", bins=30, palette=PALETTE, ax=ax, multiple="layer")
    ax.set_title(col)
plt.tight_layout(); plt.savefig("figs/03_numeric_hist.png"); plt.show()

# Box plots make the shift between the two classes easier to read
fig, axes = plt.subplots(1, 3, figsize=(12, 3.6))
for ax, col in zip(axes, ["Discount_offered", "Weight_in_gms", "Cost_of_the_Product"]):
    sns.boxplot(x="Late", y=col, data=df, palette=PALETTE, ax=ax)
    ax.set_xticklabels(["On time", "Late"]); ax.set_xlabel("")
    ax.set_title(f"{col} by outcome")
plt.tight_layout(); plt.savefig("figs/04_boxplots.png"); plt.show()

