# Correlation of each feature with the target, sorted
RESULTS["corr_with_target"] = corr["Late"].drop("Late").round(3).to_dict()
print(corr["Late"].drop("Late").sort_values().to_string())

"""## 5. Feature Engineering

Categorical variables cannot be fed directly to scikit-learn models, so they are **one-hot encoded**
(`drop_first=True` avoids the dummy-variable trap).
"""

# Separate the predictors (X) from the target (y)
X = df.drop(columns=["Late"])        # all columns except the target
y = df["Late"]                       # the target column itself

# One-hot encode the four categorical columns
X = pd.get_dummies(X, columns=cat_cols, drop_first=True)

RESULTS["n_features"] = X.shape[1]   # number of model features after encoding
print("Feature matrix shape after encoding:", X.shape)
X.head()

"""## 6. Train–test split and feature scaling"""

# 80% training / 20% testing, stratified so both sets keep the same late-order ratio
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.20, random_state=RANDOM_STATE, stratify=y)

# Logistic Regression and KNN are sensitive to feature scale, so standardise the features
scaler = StandardScaler().fit(X_train)       # learn mean & sd from the TRAIN set only
X_train_sc = scaler.transform(X_train)       # apply to train
X_test_sc  = scaler.transform(X_test)        # apply the same transform to test

RESULTS["n_train"], RESULTS["n_test"] = len(X_train), len(X_test)
print(f"Training set: {len(X_train)} orders | Test set: {len(X_test)} orders")

"""## 7. Model building and evaluation

Four algorithms required by the guidelines are trained and compared with a single reusable helper function.
"""

def evaluate(name, model, Xtr, Xte, scaled=False):
    """Train a model, print its report, and return a dictionary of metrics."""
    model.fit(Xtr, y_train)                                  # train on the training data
    y_pred  = model.predict(Xte)                             # hard class predictions
    y_proba = model.predict_proba(Xte)[:, 1]                 # probability of class 1 (late)

    metrics = {                                              # collect the five headline metrics
        "Model":     name,
        "Accuracy":  round(accuracy_score(y_test, y_pred), 3),
        "Precision": round(precision_score(y_test, y_pred), 3),
        "Recall":    round(recall_score(y_test, y_pred), 3),
        "F1":        round(f1_score(y_test, y_pred), 3),
        "ROC_AUC":   round(roc_auc_score(y_test, y_proba), 3),
    }
    print(f"\n{'='*60}\n{name}\n{'='*60}")
    print(classification_report(y_test, y_pred, target_names=["On time", "Late"]))
    print("Confusion matrix:\n", confusion_matrix(y_test, y_pred))
    return metrics, model, y_proba, y_pred

# Dictionary of the four candidate models (the boolean flag says whether to use scaled data)
models = {
    "Logistic Regression": (LogisticRegression(max_iter=1000, random_state=RANDOM_STATE), True),
    "K-Nearest Neighbors": (KNeighborsClassifier(n_neighbors=15), True),
    "Decision Tree":       (DecisionTreeClassifier(max_depth=6, random_state=RANDOM_STATE), False),
    "Random Forest":       (RandomForestClassifier(n_estimators=300, max_depth=10,
                                                   random_state=RANDOM_STATE), False),
}

scores, fitted, probas, preds = [], {}, {}, {}      # containers for results
for name, (model, needs_scaling) in models.items():
    Xtr, Xte = (X_train_sc, X_test_sc) if needs_scaling else (X_train, X_test)
    m, fit, proba, pred = evaluate(name, model, Xtr, Xte)
    scores.append(m); fitted[name] = fit; probas[name] = proba; preds[name] = pred

# Put all results side by side in a comparison table, sorted by accuracy
results_df = pd.DataFrame(scores).sort_values("Accuracy", ascending=False).reset_index(drop=True)
RESULTS["model_table"] = results_df.to_dict("records")
results_df

# Grouped bar chart comparing every metric across the four models
plot_df = results_df.melt(id_vars="Model", var_name="Metric", value_name="Score")

plt.figure(figsize=(9,4))
sns.barplot(data=plot_df, x="Model", y="Score", hue="Metric", palette="Blues_d")
plt.title("Model comparison on the test set"); plt.ylim(0, 1); plt.xlabel("")
plt.legend(ncol=5, fontsize=8, loc="upper center")
plt.tight_layout(); plt.savefig("figs/07_model_comparison.png"); plt.show()

"""### 7.1 Cross-validation check (5-fold)"""

# 5-fold cross-validation on the full dataset guards against a lucky train/test split
for name, (model, needs_scaling) in models.items():
    data = scaler.fit_transform(X) if needs_scaling else X          # scale only where needed
    cv = cross_val_score(model, data, y, cv=5, scoring="accuracy")  # 5 accuracy scores
    RESULTS[f"cv_{name}"] = round(cv.mean(), 3)
    print(f"{name:<22} CV accuracy = {cv.mean():.3f} (+/- {cv.std():.3f})")

"""### 7.2 Best model — confusion matrix and ROC curves"""

# The best model is the one with the highest test accuracy
best_name = results_df.loc[0, "Model"]
RESULTS["best_model"] = best_name
print("Best model by accuracy:", best_name)

# Confusion matrix of the best model as an annotated heatmap
cm = confusion_matrix(y_test, preds[best_name])
RESULTS["best_cm"] = cm.tolist()

plt.figure(figsize=(4.8,4))
sns.heatmap(cm, annot=True, fmt="d", cmap="Blues", cbar=False,
            xticklabels=["On time", "Late"], yticklabels=["On time", "Late"])
plt.xlabel("Predicted"); plt.ylabel("Actual"); plt.title(f"Confusion matrix - {best_name}")
plt.tight_layout(); plt.savefig("figs/08_confusion_matrix.png"); plt.show()

# Full classification report of the best model, stored for the slides
RESULTS["best_report"] = classification_report(y_test, preds[best_name],
                                               target_names=["On time", "Late"], output_dict=True)

# ROC curves of all four models on one axis
plt.figure(figsize=(5.6,4.4))
for name in models:
    fpr, tpr, _ = roc_curve(y_test, probas[name])                   # false/true positive rates
    plt.plot(fpr, tpr, label=f"{name} (AUC = {roc_auc_score(y_test, probas[name]):.3f})")
plt.plot([0,1], [0,1], "--", color="grey", label="Random guess")    # diagonal reference line
plt.xlabel("False Positive Rate"); plt.ylabel("True Positive Rate")
plt.title("ROC curves"); plt.legend(fontsize=8)
plt.tight_layout(); plt.savefig("figs/09_roc.png"); plt.show()

"""## 8. Feature importance analysis"""

# Random Forest exposes how much each feature reduced impurity across all trees
rf = fitted["Random Forest"]
importance = pd.Series(rf.feature_importances_, index=X.columns).sort_values(ascending=False)
RESULTS["feature_importance"] = importance.round(3).to_dict()

plt.figure(figsize=(7.5,4.5))
sns.barplot(x=importance.values[:10], y=importance.index[:10], palette="Blues_r")
