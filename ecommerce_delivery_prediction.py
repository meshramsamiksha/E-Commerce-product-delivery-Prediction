# Pattern 2: shipments weighing between 2,000 g and 4,000 g are always late
mid_wt = df[(df["Weight_in_gms"] > 2000) & (df["Weight_in_gms"] < 4000)]
RESULTS["wt_2to4k_late_pct"] = round(mid_wt["Late"].mean()*100, 1)
RESULTS["wt_2to4k_n"] = int(len(mid_wt))

print(f"Orders with discount > 10%   : {RESULTS['disc_gt10_n']:>5}  ->  {RESULTS['disc_gt10_late_pct']}% late")
