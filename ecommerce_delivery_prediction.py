# Scatter plot that shows both effects at once
plt.figure(figsize=(7,4))
sns.scatterplot(data=df.sample(4000, random_state=RANDOM_STATE), x="Weight_in_gms", y="Discount_offered",
                hue="Late", palette=PALETTE, alpha=0.5, s=14)
plt.title("Weight vs Discount, coloured by delivery outcome")
