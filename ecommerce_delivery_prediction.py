df.describe().T

# Descriptive statistics for the categorical (object) columns
df.describe(include="object").T

"""## 3. Data quality checks"""

# Count missing values per column - the sum should be zero for this dataset
print("Total missing values:", df.isnull().sum().sum())

# Count fully duplicated rows
print("Duplicate rows      :", df.duplicated().sum())

# ID is only a row identifier and carries no predictive information -> drop it
df = df.drop(columns=["ID"])

# Rename the awkward target column to a short, readable name
df = df.rename(columns={"Reached.on.Time_Y.N": "Late"})

# Store the data-quality facts for the presentation
RESULTS["rows"], RESULTS["cols"] = df.shape[0], df.shape[1]
RESULTS["missing"] = int(df.isnull().sum().sum())
RESULTS["duplicates"] = int(df.duplicated().sum())
