from sklearn.model_selection import train_test_split, cross_val_score   # split data / cross-validate
from sklearn.preprocessing import StandardScaler                        # scale features to mean 0, sd 1

# ---- Machine learning: the four algorithms required by the guidelines ----
from sklearn.linear_model import LogisticRegression      # linear baseline classifier
from sklearn.tree import DecisionTreeClassifier          # single interpretable tree
from sklearn.ensemble import RandomForestClassifier      # ensemble of many trees (bagging)
from sklearn.neighbors import KNeighborsClassifier       # distance-based classifier

# ---- Machine learning: evaluation metrics ----
from sklearn.metrics import (accuracy_score, confusion_matrix, classification_report,
                             precision_score, recall_score, f1_score,
                             roc_auc_score, roc_curve)   # the full evaluation toolkit

warnings.filterwarnings("ignore")        # hide version/deprecation warnings for a clean notebook
sns.set_theme(style="whitegrid")         # consistent seaborn look for every chart
plt.rcParams["figure.dpi"] = 110         # sharper inline figures
PALETTE = ["#328CC1", "#0B3C5D"]         # project colour palette (blue = on time, navy = late)
