"""## 4. Exploratory Data Analysis (EDA)

### 4.1 Target variable — how many orders are late?
"""

# Count how many orders fall in each class of the target
counts = df["Late"].value_counts().sort_index()          # 0 = on time, 1 = late
RESULTS["late_rate"] = round(df["Late"].mean()*100, 1)   # percentage of late orders
RESULTS["n_late"], RESULTS["n_ontime"] = int(counts[1]), int(counts[0])

plt.figure(figsize=(5,3.5))                              # create a small figure
ax = sns.countplot(x="Late", data=df, palette=PALETTE)   # seaborn bar chart of class counts
