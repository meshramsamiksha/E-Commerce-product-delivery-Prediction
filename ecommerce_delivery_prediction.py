RESULTS["avg_discount"] = df.groupby("Late")["Discount_offered"].mean().round(1).to_dict()
RESULTS["avg_weight"]   = df.groupby("Late")["Weight_in_gms"].mean().round(0).to_dict()
print("Average discount by class:", RESULTS["avg_discount"])
print("Average weight by class  :", RESULTS["avg_weight"])

